// ─── Source file manifest ─────────────────────────────────────────────────────
const NATIVE_FILES = [
  { name: 'TelecomWidgetAttributes.swift', content: TELECOM_WIDGET_ATTRIBUTES_SWIFT },
  { name: 'TelecomActivityModule.swift',   content: TELECOM_ACTIVITY_MODULE_SWIFT   },
  { name: 'TelecomActivityModule.m',       content: TELECOM_ACTIVITY_MODULE_M       },
];

// ─── Plugin Step 1: Write source files to ios/{ProjectName}/ ─────────────────
function withTelecomNativeFiles(config) {
  return withDangerousMod(config, [
    'ios',
    async (config) => {
      const projectRoot = config.modRequest.platformProjectRoot; // …/ios
      const projectName = config.modRequest.projectName;         // TelecomWidget
      const destDir     = path.join(projectRoot, projectName);
      fs.mkdirSync(destDir, { recursive: true });

      for (const { name, content } of NATIVE_FILES) {
        fs.writeFileSync(path.join(destDir, name), content, 'utf8');
      }

      // Ensure bridging header imports RCTBridgeModule.h (idempotent)
      const bridgingHeaderPath = path.join(destDir, `${projectName}-Bridging-Header.h`);
      if (fs.existsSync(bridgingHeaderPath)) {
        let header = fs.readFileSync(bridgingHeaderPath, 'utf8');
        if (!header.includes('<React/RCTBridgeModule.h>')) {
          header += '\n#import <React/RCTBridgeModule.h>\n';
          fs.writeFileSync(bridgingHeaderPath, header, 'utf8');
        }
      }

      console.log(`[withTelecomWidgets] Native bridge files written to ${destDir}`);
      return config;
    },
  ]);
}

// ─── Plugin Step 2: Register files in Xcode project compile sources ───────────
function withTelecomXcodeFiles(config) {
  return withXcodeProject(config, (config) => {
    const xcodeProject = config.modResults;
    const projectName  = config.modRequest.projectName;
    const targetKey    = xcodeProject.findTargetKey(projectName);

    if (!targetKey) {
      console.warn(`[withTelecomWidgets] Xcode target not found: ${projectName}`);
      return config;
    }

    // Locate the PBXGroup that represents the main app source folder
    const pbxGroups = xcodeProject.hash.project.objects['PBXGroup'] ?? {};
    let appGroupKey = null;
    for (const [key, group] of Object.entries(pbxGroups)) {
      if (key.endsWith('_comment')) continue;
      if (group.path === projectName || group.name === projectName) {
        appGroupKey = key;
        break;
      }
    }

    if (!appGroupKey) {
      console.warn(`[withTelecomWidgets] PBXGroup not found for "${projectName}". Skipping.`);
      return config;
    }

    // Collect paths already in the project to avoid duplicate entries
    const existingPaths = new Set(
      Object.values(xcodeProject.hash.project.objects['PBXFileReference'] ?? {})
        .filter(r => r && typeof r === 'object' && r.path)
        .map(r => r.path)
    );

    for (const { name } of NATIVE_FILES) {
      const filePath = `${projectName}/${name}`;
      if (existingPaths.has(name) || existingPaths.has(filePath)) {
        console.log(`[withTelecomWidgets] ${name} already registered — skipping.`);
        continue;
      }
      xcodeProject.addSourceFile(filePath, { target: targetKey }, appGroupKey);
      console.log(`[withTelecomWidgets] Added ${filePath} to target "${projectName}".`);
    }

    return config;
  });
}

// ─── Main export ──────────────────────────────────────────────────────────────
const withTelecomWidgets = (config) => {
  // 1. App Group entitlement
  config = withEntitlementsPlist(config, (c) => {
    c.modResults['com.apple.security.application-groups'] = ['group.com.telecom.widget'];
    return c;
  });

  // 2. Info.plist — Live Activities support
  config = withInfoPlist(config, (c) => {
    c.modResults['NSSupportsLiveActivities']               = true;
    c.modResults['NSSupportsLiveActivitiesFrequentUpdates'] = true;
    return c;
  });

  // 3. Write Swift + ObjC source files into the iOS project
  config = withTelecomNativeFiles(config);

  // 4. Register them in the Xcode project compile sources
  config = withTelecomXcodeFiles(config);

  return config;
};

module.exports = withTelecomWidgets;

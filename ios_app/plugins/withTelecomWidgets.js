/**
 * withTelecomWidgets.js
 *
 * Expo config plugin that:
 *  1. Sets App Group entitlement on the main app
 *  2. Sets NSSupportsLiveActivities in Info.plist
 *  3. Writes TelecomActivityModule native bridge files directly into
 *     ios/{ProjectName}/ using @objc + RCT_EXTERN_MODULE (no Expo
 *     autolinking or pod required — works reliably in all CI environments)
 *  4. Registers those files in the Xcode project's main app compile sources
 *  5. Ensures the bridging header imports RCTBridgeModule.h
 */

const {
  withInfoPlist,
  withEntitlementsPlist,
  withDangerousMod,
  withXcodeProject,
} = require('@expo/config-plugins');
const path = require('path');
const fs   = require('fs');

// ─── Swift: TelecomWidgetAttributes ──────────────────────────────────────────
// Must exist in BOTH the main app target (written here) AND in the widget
// extension target (targets/widgets/TelecomWidgetAttributes.swift).
// ActivityKit requires the identical ActivityAttributes type in both binaries.

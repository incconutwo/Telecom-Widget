// ─── Swift: TelecomActivityModule ─────────────────────────────────────────────
// Classic React Native bridge via @objc + RCT_EXTERN_MODULE.
// Does NOT use ExpoModulesCore — no autolinking required.
// NativeModules.TelecomActivityModule is always available at runtime.
const TELECOM_ACTIVITY_MODULE_SWIFT = `// Auto-generated by withTelecomWidgets.js — do not edit manually.
import Foundation
import ActivityKit
import WidgetKit

@objc(TelecomActivityModule)
class TelecomActivityModule: NSObject {

  @objc static func requiresMainQueueSetup() -> Bool { return false }

  // MARK: - Widget Data

  @objc func updateWidgetData(
    _ options: NSDictionary,
    resolve: @escaping RCTPromiseResolveBlock,
    reject: @escaping RCTPromiseRejectBlock
  ) {
    telecomSaveToUserDefaults(options: options as? [String: Any] ?? [:])
    resolve(["status": "success"])
  }

  @objc func syncAllAccounts(
    _ options: NSDictionary,
    resolve: @escaping RCTPromiseResolveBlock,
    reject: @escaping RCTPromiseRejectBlock
  ) {
    guard let ud = UserDefaults(suiteName: "group.com.telecom.widget") else {
      reject("APP_GROUP_ERROR", "Cannot access App Group UserDefaults", nil)
      return
    }
    let dict = options as? [String: Any] ?? [:]
    ud.set(dict["activeAccountId"] as? String ?? "", forKey: "active_account_id")
    ud.set(dict["accountsJson"]    as? String ?? "[]", forKey: "all_accounts_data")
    ud.synchronize()
    if #available(iOS 14.0, *) { WidgetCenter.shared.reloadAllTimelines() }
    resolve(["status": "synced"])
  }

  // MARK: - Live Activity

  @objc func startOrUpdateActivity(
    _ options: NSDictionary,
    resolve: @escaping RCTPromiseResolveBlock,
    reject: @escaping RCTPromiseRejectBlock
  ) {
    guard #available(iOS 16.1, *) else {
      resolve(["status": "unsupported"])
      return
    }
    guard ActivityAuthorizationInfo().areActivitiesEnabled else {
      reject("ACTIVITIES_DISABLED", "Live Activities are disabled in system settings", nil)
      return
    }

    let dict      = options as? [String: Any] ?? [:]
    let accountId = dict["accountId"] as? String ?? "default"

    telecomSaveToUserDefaults(options: dict)

    let contentState = TelecomWidgetAttributes.ContentState(
      operatorName:      dict["operator"]          as? String ?? "Maroc Telecom",
      phoneNumber:       dict["phoneNumber"]        as? String ?? "",
      internetRemaining: dict["internetRemaining"]  as? String ?? "0 Go",
      internetPercent:   dict["internetPercent"]    as? Double ?? 0.0,
      internetLabel:     dict["internetLabel"]      as? String ?? "Internet",
      callsRemaining:    dict["callsRemaining"]     as? String ?? "0h 00m",
      callsPercent:      dict["callsPercent"]       as? Double ?? 0.0,
      callsLabel:        dict["callsLabel"]         as? String ?? "Calls",
      timestamp:         dict["timestamp"]          as? Double ?? Date().timeIntervalSince1970
    )
    let attributes = TelecomWidgetAttributes(accountId: accountId)

    if #available(iOS 16.2, *) {
      if let existing = Activity<TelecomWidgetAttributes>.activities
          .first(where: { $0.attributes.accountId == accountId }) {
        Task {
          await existing.update(ActivityContent(state: contentState, staleDate: nil))
          resolve(["status": "updated", "id": existing.id])
        }
      } else {
        Task {
          for a in Activity<TelecomWidgetAttributes>.activities {
            await a.end(nil, dismissalPolicy: .immediate)
          }
          do {
            let activity = try Activity.request(
              attributes: attributes,
              content:    ActivityContent(state: contentState, staleDate: nil),
              pushType:   nil
            )
            resolve(["status": "started", "id": activity.id])
          } catch {
            reject("REQUEST_FAILED", error.localizedDescription, error as NSError)
          }
        }
      }
    } else {
      // iOS 16.1
      if let existing = Activity<TelecomWidgetAttributes>.activities
          .first(where: { $0.attributes.accountId == accountId }) {
        Task {
          await existing.update(using: contentState)
          resolve(["status": "updated", "id": existing.id])
        }
      } else {
        Task {
          do {
            let activity = try Activity.request(
              attributes:   attributes,
              contentState: contentState,
              pushType:     nil
            )
            resolve(["status": "started", "id": activity.id])
          } catch {
            reject("REQUEST_FAILED", error.localizedDescription, error as NSError)
          }
        }
      }
    }
  }

  @objc func stopActivity(
    _ resolve: @escaping RCTPromiseResolveBlock,
    reject: @escaping RCTPromiseRejectBlock
  ) {
    guard #available(iOS 16.1, *) else { resolve(["status": "unsupported"]); return }
    Task {
      for a in Activity<TelecomWidgetAttributes>.activities {
        if #available(iOS 16.2, *) {
          await a.end(nil, dismissalPolicy: .immediate)
        } else {
          await a.end(using: nil, dismissalPolicy: .immediate)
        }
      }
      resolve(["status": "stopped"])
    }
  }

  @objc func isActivityActive(
    _ resolve: @escaping RCTPromiseResolveBlock,
    reject: @escaping RCTPromiseRejectBlock
  ) {
    guard #available(iOS 16.1, *) else { resolve(false); return }
    resolve(!Activity<TelecomWidgetAttributes>.activities.isEmpty)
  }
}

// MARK: - Shared UserDefaults helper

private func telecomSaveToUserDefaults(options: [String: Any]) {
  guard let ud = UserDefaults(suiteName: "group.com.telecom.widget") else { return }
  ud.set(options["operator"]          as? String ?? "Maroc Telecom", forKey: "widget_operator")
  ud.set(options["phoneNumber"]       as? String ?? "",              forKey: "widget_phone")
  ud.set(options["internetRemaining"] as? String ?? "0 Go",          forKey: "widget_internet")
  ud.set(options["internetPercent"]   as? Double ?? 0.0,             forKey: "widget_internet_percent")
  ud.set(options["internetLabel"]     as? String ?? "Internet",      forKey: "widget_internet_label")
  ud.set(options["callsRemaining"]    as? String ?? "0h 00m",        forKey: "widget_calls")
  ud.set(options["callsPercent"]      as? Double ?? 0.0,             forKey: "widget_calls_percent")
  ud.set(options["callsLabel"]        as? String ?? "Calls",         forKey: "widget_calls_label")
  ud.set(options["mainBalance"]       as? String ?? "",              forKey: "widget_main_balance")
  ud.set(
    options["timestamp"] as? Double ?? Date().timeIntervalSince1970,
    forKey: "widget_timestamp"
  )
  ud.synchronize()
  if #available(iOS 14.0, *) { WidgetCenter.shared.reloadAllTimelines() }
}
`;

// ─── Objective-C: RCT_EXTERN_MODULE bridge ────────────────────────────────────
